package ru.dargen.evoplus.api.ui;

/** Прокручиваемая колонка фиксированного размера. Дети кладутся в {@link #getContent()}. */
public interface UiScroll extends UiElement<UiScroll> {

    UiContainer getContent();

    /** К началу списка. */
    UiScroll scrollToTop();

    /** К концу списка — например, к последнему сообщению. Срабатывает и для только что добавленных детей. */
    UiScroll scrollToBottom();

    /** Долистано ли до конца (с допуском в пару пикселей). */
    boolean isAtBottom();

    /** Сколько содержимого прокручено от начала, в единицах интерфейса. */
    double getScrollOffset();

    /** Наибольшее смещение: на сколько содержимое длиннее видимой области (0 — листать нечего). */
    double getMaxScroll();

    /**
     * Держит ребёнка на том же месте видимой области, пока раскладка вокруг него меняется:
     * над ним добавляют или убирают детей, у соседей меняется высота. Звать до изменения —
     * например, перед тем как подгрузить старые сообщения в начало списка. Действует до
     * следующей прокрутки игроком или около полсекунды.
     */
    UiScroll keepInView(UiElement<?> child);

    /** Прокручивает так, чтобы ребёнок оказался в верхней трети видимой области. */
    UiScroll reveal(UiElement<?> child);

}
