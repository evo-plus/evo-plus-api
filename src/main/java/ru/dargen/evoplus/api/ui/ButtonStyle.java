package ru.dargen.evoplus.api.ui;

/** Стандартные кнопки EvoPlus — те же, что в окнах самого мода. */
public enum ButtonStyle {

    /** Обычное действие: отмена, закрыть, открыть страницу. */
    SECONDARY,

    /** Главное действие окна. */
    PRIMARY,

    /** Подтверждение: сохранить, принять, установить. */
    SUCCESS,

    /** Необратимое: удалить, очистить. */
    DANGER

}
