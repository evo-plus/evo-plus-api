package ru.dargen.evoplus.api.ui;

/** Стандартные начертания текста. */
public enum TextStyle {

    /** Заголовок окна: крупнее и с тенью. */
    TITLE,

    /** Основной текст. */
    BODY,

    /** Пояснение, подпись к полю. */
    SECONDARY,

    /** Второстепенное: время, счётчики, пустое состояние. */
    MUTED

}
