package ru.dargen.evoplus.api.ui.theme;

/** Что за подложку рисует {@link SurfaceRenderer}. */
public enum SurfaceKind {

    /** Всё прочее: полосы, разделители, подсветки, части окон. */
    PLAIN,

    /** Окно целиком: меню настроек, окна, диалоги. */
    WINDOW,

    /** Всплывающее поверх окна: выпадающий список, контекстное меню, подсказка. */
    POPUP,

    /** Строка или карточка списка. */
    CARD,

    BUTTON,

    /** Поле ввода и закрытый выпадающий список. */
    FIELD,

    /** Дорожка переключателя. */
    SWITCH,

    /** Ползунок переключателя. */
    KNOB,

    /** Фон виджета HUD. */
    WIDGET,

}
