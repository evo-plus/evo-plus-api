package ru.dargen.evoplus.api.share;

import java.util.function.Consumer;

/**
 * Чем игроки делятся друг с другом через EvoPlus: настройки, таймеры боссов, чёрный список
 * боссов. Берётся у аддона: {@link ru.dargen.evoplus.api.addon.Addon#getSharing()}.
 * <p>
 * Сам EvoPlus показывает входящее уведомлением; аддон может показать его ещё и у себя —
 * например, мессенджер в переписке с отправителем.
 */
public interface Sharing {

    /**
     * Обработчик входящего — на клиентском потоке, когда игрок чем-то поделился.
     * Обработчиков может быть несколько.
     */
    void onReceive(Consumer<IncomingShare> listener);

    /**
     * Окно принятия настроек по коду: загружает, показывает, чем поделились (всё выбрано,
     * категорий, которых у игрока нет, в списке нет), и применяет выбранное.
     */
    void openImport(String code);

}
